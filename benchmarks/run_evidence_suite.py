def question_records(ids: tuple[str, ...]) -> list[dict[str, str]]:
    return [{"id": item, **PERFORMANCE_HYPOTHESES[item]} for item in ids]


def performance_cells(preset: str) -> list[dict[str, Any]]:
    """Return the external evidence map without changing production experiment cells."""
    if preset not in {"quick", "full"}:
        raise ValueError("performance preset must be quick or full")
    repetitions = 1 if preset == "quick" else 3
    logical: list[tuple[str, str, tuple[str, ...]]] = [
        (candidate, "candidate-native-configuration", ("PERF-H1", "PERF-H10"))
        for candidate in _NATIVE_CANDIDATES
    ]
    logical.append(("latest", _LATEST_PROFILES[0][0], _LATEST_PROFILES[0][1]))
    if preset == "full":
        logical.extend(
            ("latest", profile, hypothesis_ids)
            for profile, hypothesis_ids in _LATEST_PROFILES[1:]
        )
    cells = []
    for repetition in range(1, repetitions + 1):
        for candidate, profile, hypothesis_ids in logical:
            cells.append(
                {
                    "cell_name": (
                        f"PERF-CELL — {candidate} / {profile} / repetition {repetition}"
                    ),
                    "candidate": candidate,
                    "profile": profile,
                    "repetition": repetition,
                    "hypotheses": list(hypothesis_ids),
                    "questions": question_records(hypothesis_ids),
                }
            )
    return cells


def automatic_performance_cell_count(preset: str) -> int:
    return len(performance_cells(preset))


def run_text(command: list[str], repository: Path) -> str:
    process = subprocess.run(
        command, cwd=repository, text=True, capture_output=True, check=False
    )
    return process.stdout.strip() if process.returncode == 0 else "unavailable"


def file_metadata(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {"path": str(path), "present": False}
    stat = path.stat()
    return {
        "path": str(path.resolve()),
        "present": True,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "size_bytes": stat.st_size,
        "mtime_epoch_seconds": stat.st_mtime,
        "birthtime_epoch_seconds": getattr(stat, "st_birthtime", None),
    }


def environment_metadata(repository: Path) -> dict[str, Any]:
    installed = shutil.which("codebase-memory-mcp")
    return {
        "git": {
            "revision": run_text(["git", "rev-parse", "HEAD"], repository),
            "tree": run_text(["git", "rev-parse", "HEAD^{tree}"], repository),
            "branch": run_text(["git", "branch", "--show-current"], repository),
            "status_porcelain": run_text(
                ["git", "status", "--short", "--untracked-files=all"], repository
            ),
        },
        "python": {
            "executable": sys.executable,
            "version": platform.python_version(),
            "implementation": platform.python_implementation(),
        },
        "host": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "processor": platform.processor(),
        },
        "binaries": {
            "repository_build": file_metadata(
                repository / "build" / "c" / "codebase-memory-mcp"
            ),
            "installed_codebase_memory_mcp": file_metadata(Path(installed))
            if installed
            else {"present": False},
        },
    }


def container_command_suffix(container: dict[str, Any] | None) -> list[str]:
    """Return the one public container flag spelling shared by both suites."""
    if container is None:
        return []
    required = {"cpus", "memory", "workers"}
    if set(container) != required:
        raise ValueError(
            "container execution requires exactly cpus, memory, and workers"
        )
    cpus = container["cpus"]
    workers = container["workers"]
    memory = container["memory"]
    if (
        not isinstance(cpus, (int, float))
        or isinstance(cpus, bool)
        or cpus <= 0
        or not isinstance(workers, int)
        or isinstance(workers, bool)
        or workers <= 0
        or workers > cpus
        or not isinstance(memory, str)
        or not memory.strip()
    ):
        raise ValueError(
            "container cpus and workers must be positive, workers may not exceed "
            "cpus, and memory must be non-empty"
        )
    cpus_text = str(int(cpus)) if float(cpus).is_integer() else str(cpus)
    return [
        "--container",
        "--cpus",
        cpus_text,
        "--memory",
        memory,
        "--workers",
        str(workers),
    ]


def build_receipt(
    *,
    repository: Path,
    output_root: Path,
    performance_preset: str,
    hypotheses_preset: str,
    rank_build: dict[str, str],
    container: dict[str, Any] | None = None,
) -> dict[str, Any]:
    repository = repository.resolve()
    output_root = output_root.resolve()
    if hypotheses_preset != "quick":
        raise ValueError("the rank evidence preset is currently quick")
    for key in ("target", "compiler", "cflags"):
        if not rank_build.get(key):
            raise ValueError(f"rank build metadata requires non-empty {key}")
    performance_root = output_root / "performance"
    rank_root = output_root / "rank-evidence"
    rank_spec_root = rank_root / "specs"
    rank_spec = rank_spec_root / RANK_QUICK_SPEC_NAME
    execution_suffix = container_command_suffix(container)
    performance_command = [
        "uv",
        "run",
        "python",
        "benchmarks/run_experiments.py",
        f"--{performance_preset}",
        "--experiment-root",
        str(performance_root),
        *execution_suffix,
    ]
    rank_preparation_command = [
        "uv",
        "run",
        "python",
        RANK_SPEC_GENERATOR,
        "--quick-hypotheses",
        "--out-dir",
        str(rank_spec_root),
    ]
    rank_command = [
        "uv",
        "run",
        "python",
        PUBLIC_EXPERIMENT_ENTRYPOINT,
        "--matrix-spec",
        str(rank_spec),
        "--experiment-root",
        str(rank_root),
        *execution_suffix,
    ]
    cells = performance_cells(performance_preset)
    rank_profiles = rank_evidence.quick_hypothesis_profiles()
    return {
        "schema_version": 1,
        "suite": {"name": UNIFIED_SUITE_NAME},
        "execution": {
            "mode": "container" if container is not None else "native",
            "container_resources": dict(container) if container is not None else None,
            "public_entrypoint": PUBLIC_EXPERIMENT_ENTRYPOINT,
        },
        "decision_context": PR_DECISION_CONTEXT,
        "performance": {
            "name": PERFORMANCE_SUITE_NAME,
            "preset": performance_preset,
            "expected_cells": len(cells),
            "cells": cells,
            "runtime_policy": "run_to_completion",
            "public_entrypoint": PUBLIC_EXPERIMENT_ENTRYPOINT,
            "compatibility": (
                "The production preset, commands, workload, candidates, profiles, index "
                "mode, and repetitions are unchanged; this receipt adds an external "
                "cell-to-question map only."
            ),
            "command": performance_command,
            "recovery_command": performance_command,
        },
        "hypotheses": {
            "name": RANK_SUITE_NAME,
            "preset": hypotheses_preset,
            "candidate_cells": len(rank_profiles),
            "candidate_profiles": rank_profiles,
            "questions": rank_evidence.public_hypothesis_registry(),
            "runtime_policy": (
                "one repetition per fixed evidence arm over MCP; measure actual duration; "
                "no suite wall-clock target or cutoff"
            ),
            "public_entrypoint": PUBLIC_EXPERIMENT_ENTRYPOINT,
            "preparation_command": rank_preparation_command,
            "matrix_spec": str(rank_spec),
            "build": dict(sorted(rank_build.items())),
            "build_provenance": {
                "status": "declared_expectation_pending_artifact_verification",
                "expectation": dict(sorted(rank_build.items())),
                "authority": (
                    "resolved candidate, compiler, flags, and binary hashes retained by "
                    "run_experiments.py are authoritative"
                ),
            },
            "compatibility_frontend": (
                "benchmarks/autotune.py remains available for retained native binary-path "
                "workflows; it is not the public unified execution path"
            ),
            "command": rank_command,
            "recovery_command": rank_command,
        },
        "environment": environment_metadata(repository),
        "output_root": str(output_root),
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=ROOT)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT / ".worktrees" / "benchmark-experiments" / "unified-evidence",
    )
    parser.add_argument(
        "--performance-preset", choices=("quick", "full"), default="full"
    )
    parser.add_argument("--hypotheses-preset", choices=("quick",), default="quick")
    parser.add_argument(
        "--build-target",
        required=True,
        help="Exact build command/target used for the rank-candidate binary.",
    )
    parser.add_argument(
        "--compiler", required=True, help="Exact compiler identity/version."
    )
    parser.add_argument(
        "--cflags", required=True, help="Exact optimization/profiling flags."
    )
    parser.add_argument(
        "--out",
        type=Path,
        help="Receipt path; defaults to OUTPUT_ROOT/evidence-suite-receipt.json.",
    )
    parser.add_argument(
        "--container",
        action="store_true",
        help="Emit canonical container commands for both performance and rank suites.",
    )
    parser.add_argument("--cpus", type=float)
    parser.add_argument("--memory")
    parser.add_argument("--workers", type=int)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    output_root = args.output_root.expanduser().resolve()
    supplied_resources = (args.cpus, args.memory, args.workers)
    if args.container and any(value is None for value in supplied_resources):
        raise ValueError("--container requires --cpus, --memory, and --workers")
    if not args.container and any(value is not None for value in supplied_resources):
        raise ValueError("--cpus, --memory, and --workers require --container")
    receipt = build_receipt(
        repository=args.repository.expanduser().resolve(),
        output_root=output_root,
        performance_preset=args.performance_preset,
        hypotheses_preset=args.hypotheses_preset,
        rank_build={
            "target": args.build_target,
            "compiler": args.compiler,
            "cflags": args.cflags,
        },
        container=(
            {"cpus": args.cpus, "memory": args.memory, "workers": args.workers}
            if args.container
            else None
        ),
    )
    output_root.mkdir(parents=True, exist_ok=True)
    destination = (
        args.out.expanduser().resolve()
        if args.out
        else output_root / "evidence-suite-receipt.json"
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        json.dumps({"receipt": str(destination), "suite": UNIFIED_SUITE_NAME}, indent=2)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
