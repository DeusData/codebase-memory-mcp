#!/usr/bin/env python3
"""Generate the rank-quality campaign's matrix specs from one definition.

Why generated rather than checked in
------------------------------------
`index_mode` is a spec-level field (`run_experiments.py:1301`), so one spec observes one
index mode and the silent-drop comparison needs three otherwise-identical specs. Three
hand-maintained near-copies drift, and a drifted arm confounds coverage loss with
whatever else changed. One definition emitting three specs cannot drift, and
`test_coverage_specs_differ_only_in_index_mode` proves it each run.

The generated bytes are measured input: `run_container_experiment.py` hashes the spec
into the container run key, so generation has to be deterministic. It is a pure function
of `corpora-v1.json` and this file's constants.

Usage:
    python3 benchmarks/campaign_specs.py --out-dir /durable/path/campaign-specs
    python3 benchmarks/campaign_specs.py --print rank-quality
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

try:  # Package import under tests; script-local import for direct execution.
    from benchmarks import rank_hypotheses as rank_evidence
except ModuleNotFoundError:  # pragma: no cover - direct script execution
    import rank_hypotheses as rank_evidence

BENCHMARKS = Path(__file__).resolve().parent
QUERY_MANIFEST = "benchmarks/rank-queries-v1/manifest.json"
CORPUS_MANIFEST = "benchmarks/corpora-v1.json"

# The popularity cohort: real OSS, pinned by commit and tree, each chosen for a stated
# discriminating condition (corpora-v1.json "discriminates"). The four mined-workload
# repositories are deliberately absent: they resolve their revision at run time from a
# local checkout, so they cannot be pin-verified before staging and would weaken the
# reproducibility the container coordinator exists to provide. Run them natively.
# scikit-learn is here for domain rather than language: it is Python like flask, but
# flask's "test" occurrences are scaffolding while sklearn's are public API
# (train_test_split, test_size, hypothesis testing). Without it every corpus comes from a
# domain where the hardcoded criteria happen to hold, which under-samples the failure
# the campaign exists to find.
POPULARITY_CORPORA = (
    "cosign",
    "jest",
    "runc",
    "flask",
    "redis",
    "ripgrep",
    "scikit-learn",
)

# H1-H5 compare orderings over one graph, so they must not also vary coverage. Full
# indexing removes FAST_SKIP_DIRS from the comparison entirely.
RANK_INDEX_MODE = "full"
COVERAGE_INDEX_MODES = ("full", "moderate", "fast")

# Reply detail is a measured determinant of answer quality, not presentation: upstream
# #1382 recorded recall 0.723 -> 0.525 on jackrabbit-oak purely from the graph arm
# returning less. Sweeping it alongside a ranking change is what separates "ordered
# better" from "returned more". Keys verified against config-keys-v1.json.
DETAIL_PROFILES: tuple[tuple[str, dict[str, str]], ...] = (
    (
        "detail-lean",
        {"search_limit": "10", "trace_max_results": "10", "snippet_max_lines": "40"},
    ),
    ("detail-default", {}),
    (
        "detail-rich",
        {"search_limit": "200", "trace_max_results": "100", "snippet_max_lines": "400"},
    ),
)
# One corpus carries the detail frontier. Crossing every corpus with every detail level
# would triple the campaign for a question that is about the detail axis, not the corpus.
DETAIL_FRONTIER_CORPUS = "cosign"

CAPABILITY_SUPPORT = {"rank": True}

# Every runtime knob that can change a published ranking score, from
# src/pagerank/pagerank.h:89-101,113-222 and validated against config-keys-v1.json.
# A knob absent from this set is one the campaign never proved does anything, and a
# sweep over it would report a difference of exactly zero whether it is live or inert.
RANKING_KNOBS = rank_evidence.RANK_OPTION_GROUPS["ranking_semantics"]
# epsilon and max_iter are numerics rather than semantics: changing them changes how
# precisely the same fixed point is reached, not which one. Sweeping them here would
# report convergence noise as knob efficacy.
NUMERIC_KNOBS = rank_evidence.RANK_OPTION_GROUPS["numerical_convergence_controls"]
PARAMETER_CONTRACTS = rank_evidence.parameter_macro_contracts()


def declared_intervention(option: str) -> tuple[str, dict[str, str]]:
    """Pick a non-default endpoint from the product's declared/recommended range."""
    contract = PARAMETER_CONTRACTS[option]
    if option == "pagerank_max_iter":
        field = "declared_min"
    elif contract.get("recommended_max") != contract["default"]:
        field = "recommended_max"
    else:
        field = "recommended_min"
    return contract[field], {
        "option": option,
        "selected_field": field,
        "value": contract[field],
        "source": contract["source"],
        "macros": contract["macros"],
    }


def corpus_arguments(corpus_id: str) -> list[str]:
    """Workload flags that point one cell at one corpus.

    --capability-quality and --index-mode are experiment-owned
    (BENCHMARK_ARGS_RESERVED_FLAGS, run_experiments.py:115-140) and are set by the spec
    fields instead; passing them here is rejected at validation time.
    """
    return [
        "--corpus",
        corpus_id,
        "--rank-query-manifest",
        QUERY_MANIFEST,
        "--corpus-manifest",
        CORPUS_MANIFEST,
    ]


def base_spec(
    *,
    harness_version: str,
    campaign_arm: str,
    index_mode: str,
    profiles: list[dict[str, Any]],
    ref: str,
    repetitions: int,
    timeout_seconds: int,
) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "identity_version": 2,
        "harness_version": harness_version,
        "campaign_arm": campaign_arm,
        "benchmark_script": "benchmarks/run_benchmark.py",
        "cwd": ".",
        "repetitions": repetitions,
        "timeout_seconds": timeout_seconds,
        "execution_order": "paired_interleaved",
        "transports": ["mcp"],
        "index_mode": index_mode,
        "capability_quality": "rank",
        "candidates": [
            {
                "label": "head",
                "ref": ref,
                "capability_support": dict(CAPABILITY_SUPPORT),
            }
        ],
        "profiles": profiles,
        # capability_quality runs force frontier_files and exact_caps to [None]
        # (run_experiments.py:1565-1567), so the scenario is a single named cell.
        "scenarios": [{"name": "rank_quality"}],
    }


def corpus_profile(
    corpus_id: str, *, label: str | None = None, overrides: dict[str, str] | None = None
) -> dict[str, Any]:
    """One cell: one corpus, optionally under one reply-detail configuration."""
    hypothesis_ids = ("H1", "H2", "H4", "H5", "H6")
    cell_label = label or f"corpus-{corpus_id}"
    return {
        "label": cell_label,
        "cell_name": f"RANK-CORPUS — {cell_label}",
        "informs_hypotheses": list(hypothesis_ids),
        "questions": [
            {
                "id": hypothesis_id,
                "name": rank_evidence.HYPOTHESES[hypothesis_id]["name"],
                "question": rank_evidence.HYPOTHESES[hypothesis_id]["question"],
            }
            for hypothesis_id in hypothesis_ids
        ],
        "config_profile": "candidate_native_configuration",
        "capabilities": {},
        "config_overrides": dict(overrides or {}),
        "benchmark_args": corpus_arguments(corpus_id),
    }


def selected_corpora(corpora: tuple[str, ...] | None) -> tuple[str, ...]:
    """Resolve the corpus set, rejecting an unknown id at generation time.

    docs/EVALUATION_PLAN.md asks for a pilot before a sweep, so a one-corpus run is a
    first-class mode rather than something to hand-edit a generated spec for. An
    unrecognised id would otherwise fail after the image build and the candidate build.
    """
    if corpora is None:
        return POPULARITY_CORPORA
    unknown = [name for name in corpora if name not in POPULARITY_CORPORA]
    if unknown:
        raise ValueError(
            f"unknown corpus id(s) {unknown}; this campaign covers "
            + ", ".join(POPULARITY_CORPORA)
        )
    return tuple(name for name in POPULARITY_CORPORA if name in set(corpora))


def build_rank_spec(
    ref: str,
    repetitions: int,
    timeout_seconds: int,
    corpora: tuple[str, ...] | None = None,
) -> dict[str, Any]:
    """Real-corpus node/edge ranking arm plus the reply-detail sweep.

    Every scorer is read from the same graph by run_rank_score_probes, so the six-way
    comparison needs one candidate rather than six. Adding PR #879's `importance` arm is
    one more candidates[] entry pointing at its ref; it reports applicable: false here.

    This arm instruments H1/H2/H4/H5/H6. It does not pair rank-on with rank-off cost or
    tune across held-out language strata, so it must not claim H3 or H7.
    """
    chosen = selected_corpora(corpora)
    profiles = [corpus_profile(corpus_id) for corpus_id in chosen]
    profiles.extend(
        corpus_profile(
            DETAIL_FRONTIER_CORPUS,
            label=f"{DETAIL_FRONTIER_CORPUS}-{name}",
            overrides=overrides,
        )
        for name, overrides in DETAIL_PROFILES
        # detail-default is already covered by the plain corpus profile
        if overrides and DETAIL_FRONTIER_CORPUS in chosen
    )
    spec = base_spec(
        harness_version="rank-quality-v1",
        campaign_arm="rank",
        index_mode=RANK_INDEX_MODE,
        profiles=profiles,
        ref=ref,
        repetitions=repetitions,
        timeout_seconds=timeout_seconds,
    )
    spec["evidence_contract"] = {
        "role": "real_corpus_rank_quality",
        "hypotheses": ["H1", "H2", "H4", "H5", "H6"],
        "not_evaluated": ["H3", "H7"],
        "independent_unit": "corpus; repetitions and detail profiles are repeated observations",
        "registry": rank_evidence.public_hypothesis_registry(),
    }
    return spec


def build_canary_spec(
    ref: str, repetitions: int, timeout_seconds: int
) -> dict[str, Any]:
    """The validity precondition: prove every ranking knob actually moves the scores.

    Runs on the synthetic rank fixture rather than a corpus. The question is whether a
    config value reaches the scorer at all, which 17 files answer as well as 3,000 do,
    and a per-corpus canary would cost minutes per knob.

    Nothing downstream is trustworthy until this passes: a knob that silently does
    nothing produces a clean run reporting a difference of exactly zero, which reads
    identically to "this knob does not help".
    """
    profiles = [
        {
            "label": "baseline",
            "cell_name": "RANK-CANARY — baseline published ranking",
            "config_profile": "candidate_native_configuration",
            "capabilities": {},
            "config_overrides": {},
            "benchmark_args": [],
            "informs_hypotheses": ["H2", "H3", "H4", "H7"],
            "questions": [
                {
                    "id": hypothesis_id,
                    "name": rank_evidence.HYPOTHESES[hypothesis_id]["name"],
                    "question": rank_evidence.HYPOTHESES[hypothesis_id]["question"],
                }
                for hypothesis_id in ("H2", "H3", "H4", "H7")
            ],
        }
    ]
    for knob in sorted(RANKING_KNOBS):
        value, parameter_source = declared_intervention(knob)
        hypothesis_ids = ("H2", "H4", "H7")
        profiles.append(
            {
                "label": f"knob-{knob}",
                "cell_name": f"RANK-CANARY — {knob} declared-range intervention",
                "config_profile": "candidate_native_configuration",
                "capabilities": {},
                "config_overrides": {knob: value},
                "benchmark_args": [],
                "parameter_sources": [parameter_source],
                "informs_hypotheses": list(hypothesis_ids),
                "questions": [
                    {
                        "id": hypothesis_id,
                        "name": rank_evidence.HYPOTHESES[hypothesis_id]["name"],
                        "question": rank_evidence.HYPOTHESES[hypothesis_id]["question"],
                    }
                    for hypothesis_id in hypothesis_ids
                ],
            }
        )
    for knob in sorted(NUMERIC_KNOBS):
        value, parameter_source = declared_intervention(knob)
        profiles.append(
            {
                "label": f"numeric-{knob}",
                "cell_name": f"RANK-CANARY — {knob} convergence control",
                "config_profile": "candidate_native_configuration",
                "capabilities": {},
                "config_overrides": {knob: value},
                "benchmark_args": [],
                "parameter_sources": [parameter_source],
                "informs_hypotheses": ["H3"],
                "questions": [
                    {
                        "id": "H3",
                        "name": rank_evidence.HYPOTHESES["H3"]["name"],
                        "question": rank_evidence.HYPOTHESES["H3"]["question"],
                    }
                ],
            }
        )
    spec = base_spec(
        harness_version="knob-canary-v1",
        campaign_arm="canary",
        index_mode=RANK_INDEX_MODE,
        profiles=profiles,
        ref=ref,
        repetitions=repetitions,
        timeout_seconds=timeout_seconds,
    )
    spec["evidence_contract"] = {
        "role": "instrument_validity",
        "hypotheses": [],
        "option_groups": ["ranking_semantics", "numerical_convergence_controls"],
        "semantic_expectation": "fingerprint changes when the fixture contains the affected edge type",
        "numerical_expectation": "publication, rank drift, and latency are measured; byte change is not required",
    }
    return spec


def build_quick_hypothesis_spec(
    ref: str = "HEAD", *, timeout_seconds: int
) -> dict[str, Any]:
    """Prioritized synthetic cells covering scorers, semantics, numerics, and lifecycle.

    This is the bounded development diagnostic used by ``run_evidence_suite.py``. It is
    intentionally not a cross-language quality verdict: a synthetic Python fixture can
    establish wiring, metric domains, publication behavior, and relative cost, while the
    real-corpus arm supplies language/task generalization evidence.
    """
    profiles = rank_evidence.quick_hypothesis_profiles()
    for profile in profiles:
        profile["benchmark_args"] = []
    spec = base_spec(
        harness_version="rank-hypotheses-quick-v2",
        campaign_arm="hypothesis_quick",
        index_mode=RANK_INDEX_MODE,
        profiles=profiles,
        ref=ref,
        repetitions=1,
        timeout_seconds=timeout_seconds,
    )
    spec["suite_name"] = rank_evidence.RANK_SUITE_NAME
    spec["runtime_policy"] = {
        "design": "one repetition per fixed evidence arm over MCP",
        "measurement": "record actual elapsed time for every cell",
    }
    spec["evidence_contract"] = {
        "role": "bounded_development_diagnostic",
        "hypotheses": ["H2", "H3", "H4", "H6"],
        "not_evaluated": ["H1", "H5", "H7"],
        "limitations": [
            "synthetic Python fixture only",
            "H6 edge ranking is instrumented but has no judged edge/path task",
            "H3 cost is a smoke estimate, not a production-scale overhead claim",
        ],
        "registry": rank_evidence.public_hypothesis_registry(),
    }
    return spec


def build_coverage_specs(
    ref: str,
    repetitions: int,
    timeout_seconds: int,
    corpora: tuple[str, ...] | None = None,
) -> list[dict[str, Any]]:
    """The silent-drop arm: identical corpora and profiles, one spec per index mode.

    The comparison is the diff between these runsets, so anything differing besides
    index_mode would be measured as coverage loss. That invariant is a test, not a
    comment: test_coverage_specs_differ_only_in_index_mode.
    """
    profiles = [corpus_profile(corpus_id) for corpus_id in selected_corpora(corpora)]
    return [
        base_spec(
            harness_version=f"coverage-{index_mode}-v1",
            campaign_arm="coverage",
            index_mode=index_mode,
            profiles=profiles,
            ref=ref,
            repetitions=repetitions,
            timeout_seconds=timeout_seconds,
        )
        for index_mode in COVERAGE_INDEX_MODES
    ]


def build_all_specs(
    ref: str = "HEAD",
    repetitions: int = 1,
    timeout_seconds: int = 2400,
    corpora: tuple[str, ...] | None = None,
) -> list[dict[str, Any]]:
    return [
        build_canary_spec(ref, repetitions, timeout_seconds),
        build_rank_spec(ref, repetitions, timeout_seconds, corpora),
        *build_coverage_specs(ref, repetitions, timeout_seconds, corpora),
    ]


def spec_filename(spec: dict[str, Any]) -> str:
    return f"{spec['harness_version']}.json"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out-dir",
        type=Path,
        help="Directory to write the generated specs into; created if absent.",
    )
    parser.add_argument(
        "--print",
        dest="print_arm",
        help="Print one spec by harness_version instead of writing files.",
    )
    parser.add_argument(
        "--ref",
        default="HEAD",
        help="Candidate Git ref measured by every arm; defaults to HEAD.",
    )
    parser.add_argument(
        "--corpora",
        default="",
        help=(
            "Comma-separated subset of the corpus set, for a pilot before the sweep. "
            "Defaults to all of: " + ", ".join(POPULARITY_CORPORA)
        ),
    )
    parser.add_argument("--repetitions", type=int, default=1)
    parser.add_argument("--timeout-seconds", type=int, default=2400)
    args = parser.parse_args(argv)

    chosen = tuple(name.strip() for name in args.corpora.split(",") if name.strip())
    try:
        specs = build_all_specs(
            args.ref, args.repetitions, args.timeout_seconds, chosen or None
        )
    except ValueError as error:
        parser.error(str(error))
    if args.print_arm:
        for spec in specs:
            if spec["harness_version"] == args.print_arm:
                print(json.dumps(spec, indent=2, sort_keys=True))
                return 0
        available = ", ".join(spec["harness_version"] for spec in specs)
        parser.error(f"unknown arm {args.print_arm!r}; available: {available}")
    if args.out_dir is None:
        parser.error("pass --out-dir to write specs, or --print <arm> to inspect one")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for spec in specs:
        path = args.out_dir / spec_filename(spec)
        path.write_text(
            json.dumps(spec, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        # Read the flag rather than a fixed position: the canary's profiles carry no
        # workload flags at all, and indexing into them crashed generation after the
        # first arm was written.
        corpora = sorted(
            {
                arguments[index + 1]
                for profile in spec["profiles"]
                for arguments in [profile["benchmark_args"]]
                for index, argument in enumerate(arguments)
                if argument == "--corpus" and index + 1 < len(arguments)
            }
        )
        scope = f"{len(corpora)} corpora" if corpora else "the synthetic fixture"
        print(f"wrote {path}: {len(spec['profiles'])} cells over {scope}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
